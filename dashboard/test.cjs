'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {validateEvidence, EVIDENCE_COLUMNS, validatePrediction, parseCSV, analyse, advanceFrame, lensBounds, orbitFraction} = require('./app.js');
// Use synthetic labels to test boundaries without shipping licensed match outputs.
const labels = Array(199319).fill('X');
labels.fill('H',11185,90652);
labels.fill('A',110808,190198);
const csv='frame,label\n'+labels.map((v,i)=>`${i},${v}`).join('\n')+'\n';
const result=validatePrediction(csv).result;
assert.equal(validatePrediction(csv.replace(/\n/g, '\r\n')).parsed.length, 199319);
assert.throws(() => validatePrediction(csv.replace('frame,label', 'frame,team')));
assert.throws(() => validatePrediction(csv.replace('0,X', '0,')));
assert.throws(() => validatePrediction(csv.replace('0,X', '0,H,extra')));
assert.throws(() => validatePrediction(csv.replace('1,X', 'NaN,X')));
assert.throws(() => validatePrediction(csv.replace('0,X', '0,H<script>')));
assert.deepEqual(result.count,{H:79467,A:79390,D:0,X:0});
assert.equal(result.spells.length,2);
assert.throws(()=>parseCSV('frame,label\n0,H'));
assert.throws(()=>parseCSV(csv.replace('0,X','0,Z')));
assert.throws(()=>parseCSV(csv.replace('1,X','0,X')));
assert.equal(analyse(Array(199319).fill('D')).spells.length,0);
assert.equal(advanceFrame(100, .1, 60, 1000), 250);
assert.equal(advanceFrame(999, .1, 60, 1000), 1000);
assert.equal(advanceFrame(100, -1, 60, 1000), 100);
assert.equal(advanceFrame(100, 5, 60, 1000), 475);
assert.deepEqual(lensBounds(11185, 11185, 90651), [11185, 12684]);
assert.deepEqual(lensBounds(90651, 11185, 90651), [89152, 90651]);
assert.deepEqual(lensBounds(50000, 11185, 90651), [49250, 50749]);
assert.deepEqual(lensBounds(5, 0, 9), [0, 9]);
assert.equal(orbitFraction(0, -1, 0, 0), 0);
assert.equal(orbitFraction(1, 0, 0, 0), .25);
assert.equal(orbitFraction(0, 1, 0, 0), .5);
assert.equal(orbitFraction(-1, 0, 0, 0), .75);
const digest='a'.repeat(64);
const evidence={schema:'devupward-evidence-v1',method:'tracking-motion-viterbi-v2',frames:199319,csv_sha256:digest,columns:EVIDENCE_COLUMNS,rows:Array(199319).fill([1,1.2,3.4,2.1,null,.4,1,.35,0,0]),review_windows:[]};
assert.equal(validateEvidence(evidence,digest),evidence);
assert.throws(()=>validateEvidence(evidence,'b'.repeat(64)));
assert.throws(()=>validateEvidence({...evidence,frames:12},digest));
assert.throws(()=>validateEvidence({...evidence,columns:[]},digest));
const invalidRows=evidence.rows.slice();invalidRows[100]=[1,1.2,3.4,2.1,null,.4,1,1.2,0,0];
assert.throws(()=>validateEvidence({...evidence,rows:invalidRows},digest));
assert.throws(()=>validateEvidence({...evidence,review_windows:[{start:0,end:99}]},digest));
console.log('PASS: CSV validation, half boundaries, playback, lens clipping and orbit mapping.');
